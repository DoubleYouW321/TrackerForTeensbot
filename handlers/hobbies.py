@hobbies_router.callback_query(F.data.startswith('s_'))
async def callback_sport(callback: CallbackQuery):
    await callback.answer()
    sport = callback.data
    
    if sport in sports:
        back_markup = get_callback_btns(btns={'⬅️ Назад к видам спорта': 'sports'})
        await callback.message.answer(sports[sport], reply_markup=back_markup)
    else:
        await callback.message.answer('😕 Информация по этому виду спорта пока недоступна.')

@hobbies_router.callback_query(F.data.startswith('iq_'))
async def callback_iq_hobbies(callback: CallbackQuery):
    await callback.answer()
    iq = callback.data
    
    if iq in iq_hobbies:
        back_markup = get_callback_btns(btns={'⬅️ Назад к интеллектуальным занятиям': 'iq'})
        await callback.message.answer(iq_hobbies[iq], reply_markup=back_markup)
